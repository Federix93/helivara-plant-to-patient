#!/usr/bin/env python3
"""Run the golden question set against both Genie agents; write evidence/genie/transcripts.{json,md}."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "checks"))
from ask_genie import ask  # noqa: E402

D, M = "01f1bc08a109177a8d192afb82da3e2b", "01f1bc08a1471942bf4433f530ef8537"
GOLDEN = [
    ("data", D, "Which launches are at risk, and is it master data, serialization, or artwork blocking them?"),
    ("data", D, "How much revenue is at risk on the Zyvanta launch, and which actions are open?"),
    ("data", D, "How is forecast accuracy by therapeutic area, and where is bias worst?"),
    ("data", D, "Which SKUs have the highest expiry-at-risk and low OTIF?"),
    ("data", D, "Quali lanci sono a rischio e cosa li blocca?"),
    ("data", M, "What is our OEE by plant, with availability, performance and quality?"),
    ("data", M, "Which critical equipment is predicted to fail in the next 30 days, and which brands are at risk?"),
    ("data", M, "What are the top root causes of major deviations?"),
    ("data", M, "What is right-first-time and schedule adherence by plant?"),
    ("data", M, "Which equipment has the highest unplanned downtime and maintenance cost?"),
    ("knowledge", D, "What makes a launch 'ready', and how is the readiness score computed?"),
    ("knowledge", D, "Why are Faringel, Digestin and Citralux exempt from serialization?"),
    ("knowledge", D, "Should I worry about Oribex demand going down?"),
]
CONTRAST = [(M, "What's our OEE by plant?"), (M, "and what does OEE mean, and why do all three components matter?")]

if __name__ == "__main__":
    out = []
    for kind, sid, q in GOLDEN:
        r = ask(sid, q)
        r["kind"] = kind
        out.append(r)
        print(f"{r['status']:9s} {kind:9s} {q}", flush=True)
    first = ask(CONTRAST[0][0], CONTRAST[0][1])
    first["kind"] = "contrast-1"
    second = ask(CONTRAST[1][0], CONTRAST[1][1], conversation_id=first["conversation_id"])
    second["kind"] = "contrast-2 (follow-up)"
    out += [first, second]
    (ROOT / "evidence/genie").mkdir(parents=True, exist_ok=True)
    (ROOT / "evidence/genie/transcripts.json").write_text(json.dumps(out, indent=1, ensure_ascii=False))
    md = ["# Genie golden-question transcripts", "",
          "Captured via the Genie Conversation API (`checks/genie_golden.py`). Agents: **Demand and Supply** "
          f"(`{D}`) and **Manufacturing and Reliability** (`{M}`). Synthetic data; Helivara is fictional.", ""]
    for i, r in enumerate(out, 1):
        agent = "Demand and Supply" if r["space_id"] == D else "Manufacturing and Reliability"
        md += [f"## {i}. [{r['kind']}] {r['question']}", "", f"*Agent:* {agent} · *status:* {r['status']}", "",
               "**Answer**", "", r["text"] or "_(no text)_", ""]
        if r["sql"]:
            md += ["**SQL generated by Genie**", "", "```sql", r["sql"], "```", ""]
        if r["rows"]:
            md += ["**First rows**", "", "| " + " | ".join(r["columns"]) + " |", "|" + "---|" * len(r["columns"])]
            md += ["| " + " | ".join("" if v is None else str(v) for v in row) + " |" for row in r["rows"][:8]] + [""]
    (ROOT / "evidence/genie/transcripts.md").write_text("\n".join(md) + "\n")
    print("wrote evidence/genie/transcripts.{json,md}")
