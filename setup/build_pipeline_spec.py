#!/usr/bin/env python3
"""Build src/pipeline/spec.py (contract types + bilingual comments + quality rules) from
evidence/contracts/gold_schemas.json and setup/comments.py. Re-run when either changes."""
import ast
import json
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from helivara.names import find_forbidden, rename  # noqa: E402

contract = json.loads((ROOT / "evidence/contracts/gold_schemas.json").read_text())
contract.pop("_scored")
src = (ROOT / "setup/comments.py").read_text()
node = next(n for n in ast.parse(src).body if isinstance(n, ast.Assign) and n.targets[0].id == "M")
comments = ast.literal_eval(node.value)
import re  # noqa: E402
comments = json.loads(re.sub(r"\(\w+'s world\)", "(launch governance)", rename(json.dumps(comments))))
comments.pop("fact_predicted_failure", None)
comments["dim_routing"] = ("Primary production routing: the main line (and plant/process step) where each SKU is made. "
                           "Links a launch to the equipment that can put its supply at risk. Instradamento produttivo.", {
    "sku": "SKU.", "primary_line": "Primary production line for this SKU.", "plant": "Plant of the primary line.",
    "process_step": "Process step on that line (e.g. coating, compression, packaging)."})

SOURCES = {}
for system, (fmt, entities) in {
    "sap": ("csv", ["dim_date", "dim_dc", "dim_line", "dim_market", "dim_plant", "dim_product", "dim_supplier",
                    "dim_launch", "dim_routing", "dim_equipment", "fact_demand_forecast", "fact_inventory", "fact_service"]),
    "mes": ("json", ["fact_batch", "fact_batch_genealogy", "fact_oee", "fact_qc_release", "fact_deviation"]),
    "iot": ("json", ["fact_equipment_telemetry"]),
    "cmms": ("csv", ["fact_maintenance"]),
    "config": ("json", ["demo_config"]),
}.items():
    for e in entities:
        SOURCES[e] = {"system": system, "format": fmt}

# expectation name -> SQL predicate (rows failing any rule are dropped from silver and kept in *_quarantine)
RULES = {
    "fact_demand_forecast": {"valid_sku": "sku IS NOT NULL", "non_negative_sales": "actual_sales >= 0"},
    "fact_inventory": {"non_negative_on_hand": "on_hand_qty >= 0"},
    "fact_service": {"valid_sku": "sku IS NOT NULL"},
    "fact_batch": {"unique_batch_id": "_dup_rank = 1"},
    "fact_batch_genealogy": {"valid_finished_lot": "finished_lot IS NOT NULL"},
    "fact_oee": {"availability_in_range": "availability BETWEEN 0 AND 1"},
    "fact_qc_release": {"valid_batch_id": "batch_id IS NOT NULL"},
    "fact_deviation": {"unique_deviation_id": "_dup_rank = 1"},
    "fact_equipment_telemetry": {"vibration_physical_range": "vibration BETWEEN 0 AND 50"},
    "fact_maintenance": {"non_negative_downtime": "downtime_min >= 0"},
}
DEDUP_KEYS = {"fact_batch": "batch_id", "fact_deviation": "deviation_id"}

assert set(contract) == set(SOURCES) == set(comments), (set(contract) ^ set(SOURCES), set(contract) ^ set(comments))
out = '"""GENERATED by setup/build_pipeline_spec.py - do not edit by hand."""\n'
for name, val in [("CONTRACT", contract), ("COMMENTS", comments), ("SOURCES", SOURCES),
                  ("RULES", RULES), ("DEDUP_KEYS", DEDUP_KEYS)]:
    out += f"\n{name} = " + pprint.pformat(val, width=110, sort_dicts=True) + "\n"
assert not find_forbidden(out), find_forbidden(out)
(ROOT / "src/pipeline/spec.py").write_text(out)
print("wrote src/pipeline/spec.py:", len(contract), "tables")

# ---- publish step: refresh the existing governed gold tables from silver (no drops) ----
import os  # noqa: E402

FQ = f"{os.getenv('CATALOG', 'fr_stable_catalog')}.{os.getenv('SCHEMA', 'supply_chain')}"


def _esc(s):
    return s.replace("'", "''")


sqlp = ["-- GENERATED by setup/build_pipeline_spec.py. Publishes silver -> existing gold tables.",
        "-- Gold tables keep their identity (certification, domains, Genie, metric views).", ""]
tc, cc = comments["dim_routing"]
cols = ",\n  ".join(f"{c} {t} COMMENT '{_esc(cc[c])}'" for c, t in contract["dim_routing"])
sqlp.append(f"CREATE TABLE IF NOT EXISTS {FQ}.dim_routing (\n  {cols}\n) COMMENT '{_esc(tc)}';\n")
for t in sorted(contract):
    sel = ", ".join(c for c, _ in contract[t])
    sqlp.append(f"INSERT OVERWRITE {FQ}.{t} SELECT {sel} FROM {FQ}.silver_{t};")
(ROOT / "src/sql").mkdir(exist_ok=True)
(ROOT / "src/sql/publish_gold.sql").write_text("\n".join(sqlp) + "\n")
print("wrote src/sql/publish_gold.sql")
